// Detailed Financials View: renders Income/Balance/Cash Flow tables (moved from monolith)
(function() {
  function render(viewType) {
    const state = window.CompanyCard?.state;
    const container = document.getElementById('financial-data-content');
    if (!container || !state?.currentStockData) return;

    const financials = state.currentStockData.API_Financials;
    if (!financials) { container.innerHTML = '<p class="text-center muted-heading">No financial data available</p>'; return; }

    const currentYear = new Date().getFullYear();
    const getValue = (root, path) => {
      if (!path) return null; const candidates = path.split('|').map(s => s.trim());
      for (const p of candidates) { const v = p.split('.').reduce((obj, key) => obj?.[key], root); if (v != null) return v; }
      return null;
    };

    const buildTable = (title, periods, metrics) => {
      const t = {
        'Revenue': 'What it is: Total sales revenue.\nWhy it matters: Shows top-line growth and demand.',
        'Net Income': "What it is: Total profit after all expenses.\nWhy it matters: The 'bottom line' indicating true profitability.",
        'EPS': "What it is: Earnings per share.\nWhy it matters: Key for shareholders; growing EPS supports higher prices.",
        'Gross Profit': 'What it is: Revenue minus cost of revenue.\nWhy it matters: Core profitability before operating expenses.',
        'Operating Expenses': 'What it is: R&D + SG&A and other operating costs.\nWhy it matters: Indicates cost discipline and scalability.',
        'Operating Income': 'What it is: Profit from core operations (EBIT).\nWhy it matters: Measures operational efficiency.',
        'EBITDA': 'What it is: Earnings before interest, taxes, depreciation, amortization.\nWhy it matters: Proxy for cash operating performance.',
        'Cost of Revenue': 'What it is: Direct costs of producing goods/services.\nWhy it matters: Gross margin driver.',
        'Net Profit Margin': 'What it is: % of revenue left as profit.\nWhy it matters: Efficiency turning sales into profit.',
        'Net Margin': 'What it is: % of revenue left as profit.\nWhy it matters: Efficiency turning sales into profit.',
        'EBITDA Margin': 'What it is: EBITDA / Revenue.\nWhy it matters: Cash generation ability from operations.',
        'Total Assets': 'What it is: Sum of all assets.\nWhy it matters: Scale and capital intensity.',
        'Current Assets': 'What it is: Assets convertible to cash within a year.\nWhy it matters: Liquidity support.',
        'Cash & Equivalents': 'What it is: Cash and near-cash items.\nWhy it matters: Immediate liquidity.',
        'Short-term Investments': 'What it is: Marketable securities < 1 year.\nWhy it matters: Additional liquid resources.',
        'Inventory': 'What it is: Goods held for sale/production.\nWhy it matters: Working capital health and demand.',
        'Property Plant Equipment': 'What it is: Tangible operating assets (net).\nWhy it matters: Capacity and capital intensity.',
        'Total Liabilities': 'What it is: All obligations owed.\nWhy it matters: Leverage and risk.',
        'Current Liabilities': 'What it is: Obligations due within a year.\nWhy it matters: Near-term liquidity needs.',
        'Total Debt': 'What it is: Short + long-term interest-bearing debt.\nWhy it matters: Financing structure and risk.',
        'Long-term Debt': 'What it is: Debt due beyond one year.\nWhy it matters: Long‑term leverage.',
        'Stockholder Equity': 'What it is: Net assets attributable to shareholders.\nWhy it matters: Capital base and solvency.',
        'Retained Earnings': 'What it is: Cumulative undistributed profits.\nWhy it matters: Reinvestment capacity.',
        'Current Ratio': 'What it is: Current assets / current liabilities.\nWhy it matters: Ability to meet short-term obligations.',
        'Quick Ratio': 'What it is: (Current assets − Inventory) / Current liabilities.\nWhy it matters: Stricter liquidity test.',
        'Debt to Equity': 'What it is: Total debt / shareholders\' equity.\nWhy it matters: Leverage and balance sheet risk.',
        'Operating Cash Flow': 'What it is: Cash generated by operations.\nWhy it matters: Core cash-earning power.',
        'Capital Expenditures': 'What it is: Spending on long-term assets.\nWhy it matters: Investment and cash needs.',
        'Free Cash Flow': 'What it is: Operating cash flow minus capex.\nWhy it matters: Funds growth, buybacks, dividends.',
        'Depreciation & Amortization': 'What it is: Non-cash expense of assets.\nWhy it matters: Bridges accounting and cash.',
        'Investing Cash Flow': 'What it is: Cash used for investments.\nWhy it matters: Capex, acquisitions, portfolio.',
        'Financing Cash Flow': 'What it is: Cash from/to financing.\nWhy it matters: Debt, buybacks, dividends.',
        'Dividends Paid': 'What it is: Cash returned to shareholders.\nWhy it matters: Capital return policy.',
        'Stock Repurchased': 'What it is: Cash spent on buybacks.\nWhy it matters: Shareholder return mechanism.',
        'Debt Repayment': 'What it is: Cash used to reduce debt.\nWhy it matters: Deleveraging and risk.'
      };

      let html = `<div class="financial-table-wrapper"><h3 class="text-lg font-semibold mb-4">${title}</h3><table class="w-full text-sm"><thead class="table-header"><tr><th class="text-left px-4 py-3 font-medium secondary-text">Metric</th>`;
      periods.forEach(p => { html += `<th class="text-right px-4 py-3 font-medium secondary-text">${p.label}</th>`; });
      html += '</tr></thead><tbody class="divide-y divide-gray-700">';

      metrics.forEach(metric => {
        html += `<tr class="hover:bg-gray-800/50 transition-colors">`;
        const tip = t[metric.name];
        html += `<td class="px-4 py-3 secondary-text" ${tip ? `data-tooltip="${tip}"` : ''}>${metric.name}</td>`;
        let previousValue = null;
        periods.forEach(period => {
          const fullPath = period.isEstimate ? `Estimates.${period.key}.${metric.key}` : `${period.key}.${metric.key}`;
          let value = getValue(financials, fullPath);
          // Aliases for key ratios if missing
          if ((value == null || value === 'N/A') && window.Aliases && !period.isEstimate) {
            const ratios = financials?.[period.key]?.Ratios; const ratiosObj = { Ratios: ratios };
            if (metric.name === 'Operating Margin') value = window.Aliases.getAliasedRatio(ratiosObj, 'operatingMargin');
            else if (metric.name === 'Gross Margin') value = window.Aliases.getAliasedRatio(ratiosObj, 'grossMargin');
            else if (metric.name === 'Net Margin' || metric.name === 'Net Profit Margin') value = window.Aliases.getAliasedRatio(ratiosObj, 'netMargin');
            else if (metric.name === 'Debt to Equity') value = window.Aliases.getAliasedRatio(ratiosObj, 'debtEquity');
          }
          let displayValue = 'N/A'; let trendClass = '';
          if (value != null) {
            const numValue = parseFloat(String(value).replace(/,/g, ''));
            if (!isNaN(numValue)) {
              if (metric.format === 'currency') displayValue = window.Formatters ? window.Formatters.formatCurrency(numValue, 1, period.currency || 'USD') : numValue.toFixed(1);
              else if (metric.format === 'percent') displayValue = (typeof value === 'string' && value.includes('%')) ? value : `${numValue.toFixed(1)}%`;
              else if (metric.format === 'quantity') displayValue = window.Formatters ? window.Formatters.formatQuantity(numValue, 2) : numValue.toFixed(2);
              else displayValue = numValue.toFixed(2);
              if (previousValue !== null && !period.isEstimate) { if (numValue > previousValue * 1.05) trendClass = 'text-green-400'; else if (numValue < previousValue * 0.95) trendClass = 'text-red-400'; }
              previousValue = numValue;
            }
          }
          const estimateClass = period.isEstimate ? 'text-blue-400' : '';
          html += `<td class="px-4 py-3 text-right font-mono ${trendClass} ${estimateClass}">${displayValue}</td>`;
        });
        html += '</tr>';
      });

      html += '</tbody></table></div>';
      return html;
    };

    const historicalPeriods = [
      { key: 'Y4', label: String(currentYear - 4), currency: financials?.Y4?.reportedCurrency },
      { key: 'Y3', label: String(currentYear - 3), currency: financials?.Y3?.reportedCurrency },
      { key: 'Y2', label: String(currentYear - 2), currency: financials?.Y2?.reportedCurrency },
      { key: 'Y1', label: String(currentYear - 1), currency: financials?.Y1?.reportedCurrency },
      { key: 'TTM', label: 'TTM', currency: financials?.TTM?.reportedCurrency }
    ];
    const estimatePeriods = [
      { key: 'Y0FWD', label: 'Y0 FWD', currency: financials?.TTM?.reportedCurrency, isEstimate: true },
      { key: 'Y1FWD', label: 'Y1 FWD', currency: financials?.TTM?.reportedCurrency, isEstimate: true },
      { key: 'Y2FWD', label: 'Y2 FWD', currency: financials?.TTM?.reportedCurrency, isEstimate: true }
    ];

    let html = '<div class="financial-tables">';
    switch ((viewType || 'income')) {
      case 'income': {
        const incomeMetrics = [
          { name: 'Revenue', key: 'Income_Statement.revenue', format: 'currency' },
          { name: 'Cost of Revenue', key: 'Income_Statement.costOfRevenue', format: 'currency' },
          { name: 'Gross Profit', key: 'Income_Statement.grossProfit', format: 'currency' },
          { name: 'Operating Expenses', key: 'Income_Statement.operatingExpenses', format: 'currency' },
          { name: 'Operating Income', key: 'Income_Statement.operatingIncome', format: 'currency' },
          { name: 'EBITDA', key: 'Income_Statement.eBITDA', format: 'currency' },
          { name: 'Net Income', key: 'Income_Statement.netIncome', format: 'currency' },
          { name: 'EPS', key: 'Income_Statement.ePS', format: 'number' },
          { name: 'Shares Outstanding', key: 'Income_Statement.weightedAverageShares|Income_Statement.weightedAverageSharesOutstanding|Income_Statement.weightedAverageSharesDiluted', format: 'quantity' }
        ];
        const marginMetrics = [
          { name: 'Gross Margin', key: 'Ratios.grossProfitMargin', format: 'percent' },
          { name: 'Operating Margin', key: 'Ratios.operatingProfitMargin', format: 'percent' },
          { name: 'Net Margin', key: 'Ratios.netProfitMargin', format: 'percent' },
          { name: 'EBITDA Margin', key: 'Ratios.eBITDAMargin', format: 'percent' }
        ];
        if (financials.Estimates) {
          const estimateMetrics = [
            { name: 'Revenue', key: 'revenueAvg', format: 'currency' },
            { name: 'EBITDA', key: 'eBITDAAvg', format: 'currency' },
            { name: 'Net Income', key: 'netIncomeAvg', format: 'currency' },
            { name: 'EPS', key: 'ePSAvg', format: 'number' }
          ];
          html += buildTable('Forward Estimates', estimatePeriods, estimateMetrics);
        }
        html += buildTable('Income Statement', historicalPeriods, incomeMetrics);
        html += buildTable('Profit Margins', historicalPeriods, marginMetrics);
        break;
      }
      case 'balance': {
        const assetMetrics = [
          { name: 'Total Assets', key: 'Balance_Sheet.totalAssets', format: 'currency' },
          { name: 'Current Assets', key: 'Balance_Sheet.totalCurrentAssets', format: 'currency' },
          { name: 'Cash & Equivalents', key: 'Balance_Sheet.cashAndCashEquivalents', format: 'currency' },
          { name: 'Short-term Investments', key: 'Balance_Sheet.shortTermInvestments', format: 'currency' },
          { name: 'Inventory', key: 'Balance_Sheet.inventory', format: 'currency' },
          { name: 'Property Plant Equipment', key: 'Balance_Sheet.propertyPlantEquipmentNet', format: 'currency' }
        ];
        const liabilityMetrics = [
          { name: 'Total Liabilities', key: 'Balance_Sheet.totalLiabilities', format: 'currency' },
          { name: 'Current Liabilities', key: 'Balance_Sheet.totalCurrentLiabilities', format: 'currency' },
          { name: 'Total Debt', key: 'Balance_Sheet.totalDebt', format: 'currency' },
          { name: 'Long-term Debt', key: 'Balance_Sheet.longTermDebt', format: 'currency' },
          { name: 'Stockholder Equity', key: 'Balance_Sheet.totalStockholderEquity', format: 'currency' },
          { name: 'Retained Earnings', key: 'Balance_Sheet.retainedEarnings', format: 'currency' }
        ];
        const ratioMetrics = [
          { name: 'Current Ratio', key: 'Ratios.currentRatio', format: 'number' },
          { name: 'Quick Ratio', key: 'Ratios.quickRatio', format: 'number' },
          { name: 'Debt to Equity', key: 'Ratios.debtEquityRatio', format: 'number' },
          { name: 'Debt to Assets', key: 'Ratios.debtToAssets', format: 'number' }
        ];
        html += buildTable('Assets', historicalPeriods, assetMetrics);
        html += buildTable('Liabilities & Equity', historicalPeriods, liabilityMetrics);
        html += buildTable('Balance Sheet Ratios', historicalPeriods, ratioMetrics);
        break;
      }
      case 'cashflow': {
        const operatingMetrics = [
          { name: 'Operating Cash Flow', key: 'Cash_Flow.netCashProvidedByOperatingActivities', format: 'currency' },
          { name: 'Capital Expenditures', key: 'Cash_Flow.capitalExpenditures', format: 'currency' },
          { name: 'Free Cash Flow', key: 'Cash_Flow.freeCashflow', format: 'currency' },
          { name: 'Depreciation & Amortization', key: 'Cash_Flow.depreciationAndAmortization', format: 'currency' }
        ];
        const investingMetrics = [
          { name: 'Investing Cash Flow', key: 'Cash_Flow.netCashUsedForInvestingActivities', format: 'currency' },
          { name: 'Acquisitions', key: 'Cash_Flow.acquisitionsNet', format: 'currency' },
          { name: 'Investments', key: 'Cash_Flow.investmentsInPropertyPlantAndEquipment', format: 'currency' }
        ];
        const financingMetrics = [
          { name: 'Financing Cash Flow', key: 'Cash_Flow.netCashUsedProvidedByFinancingActivities', format: 'currency' },
          { name: 'Dividends Paid', key: 'Cash_Flow.dividendsPaid', format: 'currency' },
          { name: 'Stock Repurchased', key: 'Cash_Flow.stockRepurchased', format: 'currency' },
          { name: 'Debt Repayment', key: 'Cash_Flow.debtRepayment', format: 'currency' }
        ];
        html += buildTable('Operating Activities', historicalPeriods, operatingMetrics);
        html += buildTable('Investing Activities', historicalPeriods, investingMetrics);
        html += buildTable('Financing Activities', historicalPeriods, financingMetrics);
        break;
      }
    }

    html += '</div>';
    container.innerHTML = html;
  }

  window.TablesView = { render };
})();
